export function report(status: ValidationReport['status'], errorCount = 0): ValidationReport {
  return {
    status,
    columns: { found: [], missing: [], unexpected: [] },
    summary: {
      rowCount: 25,
      validRowCount: errorCount ? 24 : 25,
      entityCount: 5,
      sourceCount: 1,
      periodCount: 6,
      observedPeriodCount: 6,
      missingValueCount: 1,
      errorCount,
      warningCount: 2,
      issueCounts: errorCount ? { INVALID_VALUE: errorCount } : { MISSING_VALUE: 1 },
      durationMs: 5,
    },
    issues: errorCount
      ? [
          {
            severity: 'error',
            code: 'INVALID_VALUE',
            message: '"abc" is not a number.',
            row: 7,
            column: 'value',
            entityId: 'CDR',
            value: 'abc',
          },
        ]
      : [],
    issuesTruncated: false,
  };
}

/**
 * Stands in for the Python service: CSVs containing "abc" are invalid; anything else yields the
 * committed normalized fixture (generated by the real processor), re-labelled for the version.
 * `corrupt` makes the output reference an unknown entity, which must abort the import.
 */
export class FakeProcessor implements DataProcessorClient {
  calls: ProcessCsvInput[] = [];
  corrupt = false;
  unavailable = false;

  constructor(private readonly storageRoot: string) {}

  async processCsv(input: ProcessCsvInput) {
    this.calls.push(input);
    if (this.unavailable)
      throw new ProcessorError('Data processor request failed: connect ECONNREFUSED');
    const csv = await readFile(path.join(this.storageRoot, input.sourceFilePath), 'utf8');
    const invalid = csv.includes('abc');
    const result = invalid ? report('invalid', 1) : report('valid_with_warnings');
    await this.#write(input.reportFilePath, result);
    if (invalid)
      return { report: result, outputFilePath: null, reportFilePath: input.reportFilePath };
    const normalized = JSON.parse(await readFile(FIXTURE, 'utf8')) as {
      dataset: object;
      observations: { entityId: string }[];
    };
    normalized.dataset = input.dataset;
    if (this.corrupt) normalized.observations.at(-1)!.entityId = 'GHOST';
    await this.#write(input.outputFilePath, normalized);
    return {
      report: result,
      outputFilePath: input.outputFilePath,
      reportFilePath: input.reportFilePath,
    };
  }

  validateCsv() {
    return Promise.resolve(report('valid'));
  }

  async #write(relative: string, content: unknown) {
    const target = path.join(this.storageRoot, relative);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, JSON.stringify(content));
  }
}

export type Harness = Awaited<ReturnType<typeof createHarness>>;

export async function createHarness(
  options: { csvUploadBytes?: number; mediaUploadBytes?: number; requestsPerMinute?: number } = {},
) {
  const schema = `test_${randomBytes(6).toString('hex')}`;
  const admin = new pg.Pool({ connectionString: DATABASE_URL, max: 1 });
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool = new pg.Pool({
    connectionString: DATABASE_URL,
    max: 10,
    options: `-c search_path=${schema}`,
  });
  await migrate(pool, logger);

  const storageRoot = await mkdtemp(path.join(os.tmpdir(), 'statsopedia-api-'));
  await ensureStorageDirectories(storageRoot);
  const storage = new LocalStorage(storageRoot);
  const redis = new Redis(REDIS_URL!, { maxRetriesPerRequest: null });
  const prefix = `test-${randomBytes(6).toString('hex')}`;
  const processor = new FakeProcessor(storageRoot);

  const services = buildApiServices({
    pool,
    redis,
    storage,
    processor,
    logger,
    limits: {
      csvUploadBytes: options.csvUploadBytes ?? 64 * 1024,
      mediaUploadBytes: options.mediaUploadBytes ?? 1024 * 1024,
      requestsPerMinute: options.requestsPerMinute ?? 10_000,
      uploadsPerHour: 10_000,
    },
    sessionTtlMs: 3_600_000,
    monitorEnabled: true,
    queuePrefix: prefix,
    reconcileIntervalMs: 500,
    retryDelayMs: 200,
  });
  const app = createApp({
    logger,
    service: { name: 'api', version: 'test', startedAt: new Date() },
    readinessChecks: [],
    healthCheckTimeoutMs: 1_000,
    api: services,
  });

  await upsertTemplate(pool, {
    id: TEMPLATE_ID,
    slug: 'bar-chart-race',
    version: 1,
    name: 'Bar chart race',
    description: null,
    compositionId: 'BarChartRace',
    supportedFormats: ['long', 'short'],
  });
  const passwordHash = await hashPassword(PASSWORD);
  const tokens = {} as Record<UserRole, string>;
  for (const role of ['admin', 'editor', 'viewer'] as const) {
    await insertUser(pool, {
      id: randomUUID(),
      email: `${role}@example.com`,
      name: role,
      role,
      passwordHash,
    });
    const login = await request(app)
      .post('/api/auth/login')
      .send({ email: `${role}@example.com`, password: PASSWORD });
    tokens[role] = (login.body as { token: string }).token;
  }
  const auth = (role: UserRole = 'editor') => ({ Authorization: `Bearer ${tokens[role]}` });

  return {
    app,
    pool,
    schema,
    storage,
    storageRoot,
    redis,
    prefix,
    services,
    processor,
    tokens,
    auth,
    async close() {
      await services.close();
      for (const queue of services.queues.all())
        await queue.obliterate({ force: true }).catch(() => undefined);
      await services.queues.close();
      redis.disconnect();
      await pool.end();
      await admin.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
      await admin.end();
      await rm(storageRoot, { recursive: true, force: true });
    },
  };
}

// ─── Render worker: the real runtime, with Remotion and FFmpeg replaced ───────────────────────

/** How the fake renderer behaves for the next jobs. */
export type RenderBehaviour =
  'succeed' | 'fail-once' | 'wrong-frame-count' | 'corrupt-output' | 'wait-for-cancel' | 'hang';

/**
 * Stands in for Remotion: reports the composition the render plan describes, "renders" a small
 * file with frame progress, and writes a thumbnail. Everything around it (the worker pipeline,
 * processor, PostgreSQL lifecycle, files) is the real code.
 */
export class FakeRenderer implements VideoRenderer {
  behaviour: RenderBehaviour = 'succeed';
  readonly attempts = new Map<string, number>();
  readonly compositions = new Map<string, SelectedComposition>();

  warmUp() {
    return Promise.resolve();
  }

  selectComposition({
    compositionId,
    inputProps,
  }: Parameters<VideoRenderer['selectComposition']>[0]) {
    const plan = planRaceRender(inputProps as unknown as Parameters<typeof planRaceRender>[0]);
    return Promise.resolve({
      id: compositionId,
      width: plan.width,
      height: plan.height,
      fps: plan.fps,
      durationInFrames: plan.durationInFrames + (this.behaviour === 'wrong-frame-count' ? 1 : 0),
      handle: null,
    });
  }

  async renderVideo({
    composition,
    output,
    onProgress,
    signal,
  }: Parameters<VideoRenderer['renderVideo']>[0]) {
    const jobId = path.basename(path.dirname(output));
    const attempt = (this.attempts.get(jobId) ?? 0) + 1;
    this.attempts.set(jobId, attempt);
    onProgress({ renderedFrames: 0, progress: 0 });
    if (this.behaviour === 'fail-once' && attempt === 1) throw new Error('Chrome crashed');
    if (this.behaviour === 'hang') {
      onProgress({ renderedFrames: 10, progress: 0.1 });
      await new Promise<never>(() => undefined); // a crashed worker: never finishes
    }
    if (this.behaviour === 'wait-for-cancel') {
      onProgress({ renderedFrames: 10, progress: 0.1 });
      await new Promise<never>((_, reject) => {
        if (signal.aborted) reject(new Error('aborted'));
        signal.addEventListener('abort', () => reject(new Error('aborted')));
      });
    }
    for (const share of [0.25, 0.5, 0.75, 1]) {
      onProgress({
        renderedFrames: Math.round(share * composition.durationInFrames),
        progress: share,
      });
    }
    this.compositions.set(output, composition);
    await writeFile(output, `fake mp4 ${jobId}`);
  }

  async renderThumbnail({ output }: Parameters<VideoRenderer['renderThumbnail']>[0]) {
    await writeFile(output, 'fake jpeg');
  }
}

/** Stands in for FFmpeg: probes report what was "rendered"; `corrupt-output` fails decoding. */
export function fakeMediaTools(renderer: FakeRenderer): MediaTools {
  return {
    probe(file) {
      const composition = renderer.compositions.get(file);
      return Promise.resolve({
        formatName: 'mov,mp4,m4a,3gp,3g2,mj2',
        durationSeconds: composition ? composition.durationInFrames / composition.fps : 0,
        sizeBytes: 20,
        video: composition
          ? {
              codec: 'h264',
              width: composition.width,
              height: composition.height,
              fps: composition.fps,
              frames: composition.durationInFrames,
              pixelFormat: 'yuv420p',
            }
          : null,
        audio: { codec: 'aac', sampleRate: 48_000, channels: 2 },
      });
    },
    isFaststart: () => Promise.resolve(true),
    remuxFaststart: () => Promise.reject(new Error('not expected')),
    measureLoudness: () => Promise.resolve({ integratedLufs: -18.5, truePeakDbtp: -2.1 }),
    measureEdgePeak: () => Promise.resolve(-60),
    verifyDecodes: () =>
      renderer.behaviour === 'corrupt-output'
        ? Promise.reject(new Error('Invalid NAL unit size'))
        : Promise.resolve(),
  };
}

/** Starts the real worker runtime against the harness's database, queues and storage. */
export async function startWorker(
  h: Harness,
  options: {
    renderer?: VideoRenderer;
    media?: MediaTools;
    lockDurationMs?: number;
    stalledIntervalMs?: number;
  } = {},
): Promise<WorkerRuntime & { renderer: VideoRenderer }> {
  const renderer = options.renderer ?? new FakeRenderer();
  const runtime = await startWorkerRuntime({
    connection: h.redis.duplicate({ maxRetriesPerRequest: null }),
    pool: h.pool,
    storage: h.storage,
    renderer,
    media: options.media ?? fakeMediaTools(renderer as FakeRenderer),
    logger,
    workerId: `test-worker-${randomBytes(3).toString('hex')}`,
    concurrency: { final: 2, preview: 2 },
    remotionConcurrency: null,
    timeoutMs: { preview: 120_000, final: 300_000 },
    prefix: h.prefix,
    // Short, so a "crashed" worker's job is recovered within seconds. BullMQ shares one
    // stalled-check timer per queue (the last checker's interval), so every test worker uses it.
    lockDurationMs: options.lockDurationMs ?? 5_000,
    stalledIntervalMs: options.stalledIntervalMs ?? 500,
  });
  return Object.assign(runtime, { renderer });
}
